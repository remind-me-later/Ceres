//! The structural VHDL of a netlist, one file per block: the cells of each
//! category of the schematics (`ppu-stat`, `timer`, `alu-core`...) make an
//! entity, whose ports are the wires it shares with the other blocks. The
//! entity of the module connects the blocks and holds the cells that are
//! components of their own (the CPU core in the chip).
//!
//! The wire lengths (`L_*`) and the gate widths of the loads (`W_gate_*`)
//! passed to the cells are computed as nlconv computes them for dmg-sim, so
//! that the delays are the same: the length of the wire from its drawing on
//! the die (single-precision floats), plus the lengths of the cell pins.

use std::collections::{BTreeSet, HashMap, HashSet};
use std::fmt::Write as _;

use anyhow::{Context as _, Result, bail};

use crate::File;
use crate::names::{prefixed, real_literal, vhdl_id};
use crate::netlist::{Cell, Conn, Dir, Netlist, Wire, format_f32, index_of, sv_name};
use crate::sv;

const HEADER: &str = "-- Generated by ceres-hdlgen from the netlist of dmg-schematics (CC-BY-SA 4.0).\n-- Do not edit.\n";

/// Cell types that stay at the top level of a module, outside the blocks.
const TOP_LEVEL_TYPES: &[&str] = &["sm83", "audio"];

/// The block of the cells without a category.
const OTHER: &str = "other";
const OTHER_DOC: &str = "cells outside the blocks of the schematics";

/// Generates the VHDL of a netlist module, in the order the files can be
/// analysed: the package of default lengths of its ports, a file for each
/// block, and the module (entity, and architecture `gates`).
pub fn emit(nl: &Netlist) -> Result<Vec<File>> {
    let ctx = Ctx::new(nl)?;
    let (blocks, top) = partition(&ctx)?;
    let mut files = vec![param_package(&ctx)?];
    let mut taken: HashSet<String> = ctx
        .hdl_name
        .iter()
        .map(|n| n.to_ascii_lowercase())
        .collect();
    let mut instances = String::new();
    for b in blocks.iter().filter(|b| b.count > 0) {
        let mut label = vhdl_id(&b.name.replace('-', "_"));
        if !taken.insert(label.to_ascii_lowercase()) {
            label.push_str("_block");
        }
        files.push(block_file(&ctx, b, &label)?);
        instances.push_str(&block_instance(&ctx, b, &label)?);
    }
    files.push(top_file(&ctx, &top, &instances)?);
    Ok(files)
}

/// Direction of a port of a generated entity.
#[derive(Clone, Copy, PartialEq, Eq)]
enum PortDir {
    Input,
    Output,
    Inout,
}

impl PortDir {
    const fn vhdl(self) -> &'static str {
        match self {
            Self::Input => "in",
            Self::Output => "out",
            Self::Inout => "inout",
        }
    }
}

/// A port of the module.
struct ModPort {
    /// Name in the netlist (`d[0]`).
    name: String,
    dir: PortDir,
    wire: usize,
}

/// Where a cell is: at the top level of the module, or in a block.
#[derive(Clone, Copy, PartialEq, Eq, PartialOrd, Ord)]
enum Loc {
    Top,
    Block(usize),
}

/// A block: the cells of one category, as VHDL text.
struct Block {
    /// The category (`ppu-stat`).
    name: String,
    /// What the schematics say it is (`FF41 STAT, FF44 LY & FF45 LYC`).
    doc: String,
    entity: String,
    /// Its ports: the wires it shares, with their direction.
    ports: Vec<(usize, PortDir)>,
    /// The ports of the module whose lengths its cells take.
    generics: Vec<usize>,
    signals: String,
    cells: String,
    keepers: String,
    count: usize,
}

impl Block {
    fn new(module: &str, name: &str, doc: &str) -> Self {
        Self {
            name: name.to_owned(),
            doc: doc.to_owned(),
            entity: vhdl_id(&format!("{module}_{}", name.replace('-', "_"))),
            ports: Vec::new(),
            generics: Vec::new(),
            signals: String::new(),
            cells: String::new(),
            keepers: String::new(),
            count: 0,
        }
    }

    /// The names of its generics: the length and gate width of each module
    /// port its cells are on.
    fn generic_names(&self, ctx: &Ctx<'_>) -> Vec<String> {
        self.generics
            .iter()
            .flat_map(|&p| {
                let name = &ctx.ports[p].name;
                [
                    vhdl_id(&sv_name(name, "L_")),
                    vhdl_id(&sv_name(name, "W_gate_")),
                ]
            })
            .collect()
    }
}

/// What is left at the top level: the wires shared by blocks, and the cells
/// outside them, as VHDL text.
#[derive(Default)]
struct Top {
    signals: String,
    cells: String,
    keepers: String,
}

/// A netlist module, with its settings (`define hdl-...`) and what the
/// files are made from.
struct Ctx<'a> {
    nl: &'a Netlist,
    module: String,
    cell_prefix: String,
    noprefix: Vec<String>,
    port_cell: String,
    lconv: f32,
    /// The analog wires, which are `real`.
    is_real: Vec<bool>,
    /// The ports of the module, and those on each wire.
    ports: Vec<ModPort>,
    wire_ports: Vec<Vec<usize>>,
    /// The wires that need a bus keeper.
    keeper: Vec<bool>,
    /// The VHDL name of each wire.
    hdl_name: Vec<String>,
}

impl<'a> Ctx<'a> {
    fn new(nl: &'a Netlist) -> Result<Self> {
        let strings = &nl.strings;
        let module = strings
            .get("hdl-module")
            .cloned()
            .unwrap_or_else(|| "top".to_owned());
        let real_signals: Vec<&str> = strings
            .get("hdl-real-signals")
            .map(|s| s.split_whitespace().collect())
            .unwrap_or_default();
        let mut ctx = Self {
            nl,
            cell_prefix: strings
                .get("hdl-cell-prefix")
                .cloned()
                .unwrap_or_else(|| format!("{module}_")),
            noprefix: strings
                .get("hdl-noprefix-cells")
                .map(|s| s.split_whitespace().map(str::to_owned).collect())
                .unwrap_or_default(),
            port_cell: strings
                .get("hdl-port")
                .cloned()
                .unwrap_or_else(|| "port".to_owned()),
            lconv: strings
                .get("hdl-length-conv")
                .map_or(Ok(1.0), |s| s.parse())
                .context("hdl-length-conv")?,
            module,
            is_real: nl
                .wires
                .iter()
                .map(|w| real_signals.contains(&w.signal.as_str()))
                .collect(),
            ports: Vec::new(),
            wire_ports: Vec::new(),
            keeper: Vec::new(),
            hdl_name: Vec::new(),
        };
        ctx.find_ports()?;
        ctx.find_keepers();
        ctx.name_wires()?;
        Ok(ctx)
    }

    /// The ports of the module: the connections of the wires to the port
    /// cell.
    fn find_ports(&mut self) -> Result<()> {
        let nl = self.nl;
        let port_cell = self.port_cell.clone();
        self.wire_ports = vec![Vec::new(); nl.wires.len()];
        for (wi, w) in nl.wires.iter().enumerate() {
            for c in w.sources.iter().filter(|c| c.cell == port_cell) {
                let dir = match nl.dir(c) {
                    Dir::Inout => PortDir::Inout,
                    Dir::Out | Dir::Tri | Dir::Out0 | Dir::Out1 => PortDir::Input,
                    d => bail!("port {}: invalid direction {d:?}", c.port),
                };
                self.add_port(wi, c, dir);
            }
            for c in w.drains.iter().filter(|c| c.cell == port_cell) {
                match nl.dir(c) {
                    Dir::In => self.add_port(wi, c, PortDir::Output),
                    Dir::Inout => {}
                    d => bail!("port {}: invalid direction {d:?}", c.port),
                }
            }
        }
        Ok(())
    }

    fn add_port(&mut self, wire: usize, c: &Conn, dir: PortDir) {
        self.wire_ports[wire].push(self.ports.len());
        self.ports.push(ModPort {
            name: c.port.clone(),
            dir,
            wire,
        });
    }

    /// Wires driven only by tri-state outputs keep their value with a bus
    /// keeper; for a wire on an inout port, the keeper belongs to the level
    /// above. The bits of a (0-based) vector all get one if one needs it.
    fn find_keepers(&mut self) {
        let nl = self.nl;
        self.keeper = nl
            .wires
            .iter()
            .enumerate()
            .map(|(wi, w)| {
                !w.sources.is_empty()
                    && !self.is_real[wi]
                    && !w
                        .sources
                        .iter()
                        .any(|c| matches!(nl.dir(c), Dir::Out | Dir::Out0 | Dir::Out1))
                    && !self.wire_ports[wi]
                        .iter()
                        .any(|&p| self.ports[p].dir == PortDir::Inout)
            })
            .collect();
        let mut vectors: HashMap<String, Vec<usize>> = HashMap::new();
        for (wi, w) in nl.wires.iter().enumerate() {
            if !self.is_real[wi] && index_of(&w.name).is_some() {
                let base = sv_name(&w.name[..w.name.rfind('[').unwrap_or(w.name.len())], "");
                vectors.entry(base).or_default().push(wi);
            }
        }
        for bits in vectors.values() {
            let from_0 = bits
                .iter()
                .filter_map(|&wi| index_of(&nl.wires[wi].name))
                .min()
                == Some(0);
            if from_0 && bits.iter().any(|&wi| self.keeper[wi]) {
                for &wi in bits {
                    self.keeper[wi] = true;
                }
            }
        }
    }

    /// The names of the wires: a wire on a module port takes the port's
    /// name, the others `n_<name>`.
    fn name_wires(&mut self) -> Result<()> {
        self.hdl_name = self
            .nl
            .wires
            .iter()
            .enumerate()
            .map(|(wi, w)| {
                self.wire_ports[wi].first().map_or_else(
                    || prefixed("n_", &sv_name(&w.name, "")),
                    |&p| vhdl_id(&sv_name(&self.ports[p].name, "")),
                )
            })
            .collect();
        let mut seen = HashSet::new();
        for n in &self.hdl_name {
            if !seen.insert(n.to_ascii_lowercase()) {
                bail!("two wires are called {n} in VHDL");
            }
        }
        Ok(())
    }

    /// The VHDL type of a wire. A wire with one plain output on it needs no
    /// resolution, and is faster to simulate.
    fn sig_type(&self, wi: usize) -> &'static str {
        let w = &self.nl.wires[wi];
        if self.is_real[wi] {
            "real"
        } else if self.wire_ports[wi].is_empty()
            && w.sources.len() == 1
            && self.nl.dir(&w.sources[0]) == Dir::Out
            && !self.keeper[wi]
        {
            "std_ulogic"
        } else {
            "std_logic"
        }
    }

    fn signal_decl(&self, wi: usize) -> String {
        format!("  signal {} : {};\n", self.hdl_name[wi], self.sig_type(wi))
    }

    fn keeper_instance(&self, wi: usize) -> String {
        format!(
            "  {} : entity work.keeper port map (n => {});\n",
            prefixed("k_", &sv_name(&self.nl.wires[wi].name, "")),
            self.hdl_name[wi]
        )
    }

    fn entity_of(&self, cell_type: &str) -> String {
        if self.noprefix.iter().any(|t| t == cell_type) {
            sv_name(cell_type, "")
        } else {
            sv_name(cell_type, &self.cell_prefix)
        }
    }

    /// `pkg::L_port` terms for the cell pins on a wire, and `pkg::W_gate_port`
    /// for the inputs among them.
    fn pin_terms(&self, w: &Wire) -> (Vec<String>, Vec<String>) {
        let mut wcs: Vec<_> = w.sources.iter().collect();
        wcs.extend(w.drains.iter().filter(|c| !w.sources.contains(c)));
        let (mut l, mut g) = (Vec::new(), Vec::new());
        for c in wcs {
            let Some(cell) = self.nl.cell(&c.cell) else {
                continue;
            };
            if cell.is_virtual {
                continue;
            }
            let pkg = format!(
                "work.{}",
                vhdl_id(&format!("{}_param", self.entity_of(&cell.type_name)))
            );
            let dir = self.nl.dir(c);
            l.push(format!("{pkg}.{}", vhdl_id(&sv_name(&c.port, "L_"))));
            if matches!(dir, Dir::In | Dir::Inout) {
                g.push(format!("{pkg}.{}", vhdl_id(&sv_name(&c.port, "W_gate_"))));
            }
        }
        (l, g)
    }

    /// Length of the wire on the die: the `L` attribute, or the length of
    /// its drawing; plus `L_extra`.
    #[expect(clippy::suboptimal_flops, reason = "must round like nlconv")]
    fn length(&self, w: &Wire) -> Result<(f32, bool)> {
        let given = w.attribs.get("L").map(|l| l.parse::<f32>()).transpose();
        let given = given.with_context(|| format!("wire {}: attribute L", w.name))?;
        let mut sum = given.unwrap_or(0.0);
        if given.is_none() {
            for l in &w.coords {
                let mut prev = (l[0], l[1]);
                for &[y, x] in l[2..].as_chunks::<2>().0 {
                    sum += Self::distance(prev, (y, x)) * self.lconv;
                    prev = (y, x);
                }
            }
        }
        if let Some(e) = w.attribs.get("L_extra") {
            let e: f32 = e
                .parse()
                .with_context(|| format!("wire {}: attribute L_extra", w.name))?;
            sum += e;
        }
        Ok((sum, given.is_some()))
    }

    /// The distance between two points as nlconv computes it (.NET's
    /// `Vector2.Distance`): a fused multiply-add or `hypot` would change the
    /// last bit of some lengths.
    #[expect(clippy::imprecise_flops, reason = "must round like nlconv")]
    fn distance(a: (f32, f32), b: (f32, f32)) -> f32 {
        let (dy, dx) = (b.0 - a.0, b.1 - a.1);
        (dx * dx + dy * dy).sqrt()
    }

    fn w_extra(w: &Wire) -> Result<f32> {
        w.attribs.get("W_gate_extra").map_or(Ok(0.0), |s| {
            s.parse()
                .with_context(|| format!("wire {}: attribute W_gate_extra", w.name))
        })
    }
}

/// A sum of a number (left out if 0) and terms, `0.0` if both are empty.
fn sum_expr(n: f32, terms: &[String]) -> String {
    match (n != 0.0, terms.is_empty()) {
        (true, false) => format!("{} + {}", real_literal(&format_f32(n)), terms.join(" + ")),
        (true, true) => real_literal(&format_f32(n)),
        (false, false) => terms.join(" + "),
        (false, true) => "0.0".to_owned(),
    }
}

/// Puts the cells and the wires in their blocks, or at the top level.
fn partition(ctx: &Ctx<'_>) -> Result<(Vec<Block>, Top)> {
    let nl = ctx.nl;
    let (mut blocks, cell_loc) = place_cells(ctx);
    let mut top = place_wires(ctx, &mut blocks, &cell_loc)?;
    for cell in nl.cells.iter().filter(|c| c.name != ctx.port_cell) {
        let (text, used) = instance(ctx, cell)?;
        match cell_loc[cell.name.as_str()] {
            Loc::Top => top.cells.push_str(&text),
            Loc::Block(b) => {
                let b = &mut blocks[b];
                b.cells.push_str(&text);
                b.count += 1;
                for p in used {
                    if !b.generics.contains(&p) {
                        b.generics.push(p);
                    }
                }
            }
        }
    }
    // Inputs, outputs, then inouts, each by name.
    for b in &mut blocks {
        b.ports
            .sort_by(|x, y| (x.1 as u8, &ctx.hdl_name[x.0]).cmp(&(y.1 as u8, &ctx.hdl_name[y.0])));
    }
    Ok((blocks, top))
}

/// The blocks, in the order the categories are declared, and where each
/// cell goes. Cells without a category go to `other`, except the CPU core
/// and the analog audio, which are components of their own at the top
/// level.
fn place_cells<'a>(ctx: &Ctx<'a>) -> (Vec<Block>, HashMap<&'a str, Loc>) {
    let mut blocks: Vec<Block> = ctx
        .nl
        .categories
        .iter()
        .map(|(name, doc)| Block::new(&ctx.module, name, doc))
        .collect();
    let mut cell_loc = HashMap::new();
    for cell in &ctx.nl.cells {
        let loc =
            if cell.name == ctx.port_cell || TOP_LEVEL_TYPES.contains(&cell.type_name.as_str()) {
                Loc::Top
            } else {
                let cat = if cell.category.is_empty() {
                    OTHER
                } else {
                    cell.category.as_str()
                };
                let b = blocks
                    .iter()
                    .position(|b| b.name == cat)
                    .unwrap_or_else(|| {
                        let doc = if cat == OTHER { OTHER_DOC } else { "" };
                        blocks.push(Block::new(&ctx.module, cat, doc));
                        blocks.len() - 1
                    });
                Loc::Block(b)
            };
        cell_loc.insert(cell.name.as_str(), loc);
    }
    (blocks, cell_loc)
}

/// Declares each wire inside the one block that uses it, or at the top
/// level, with a port on each block that uses it.
fn place_wires(ctx: &Ctx<'_>, blocks: &mut [Block], cell_loc: &HashMap<&str, Loc>) -> Result<Top> {
    let loc = |c: &Conn| cell_loc.get(c.cell.as_str()).copied();
    let mut top = Top::default();
    for (wi, w) in ctx.nl.wires.iter().enumerate() {
        let locs: BTreeSet<Loc> = w.sources.iter().chain(&w.drains).filter_map(loc).collect();
        if let [Loc::Block(b)] = locs.iter().copied().collect::<Vec<_>>()[..]
            && ctx.wire_ports[wi].is_empty()
        {
            blocks[b].signals.push_str(&ctx.signal_decl(wi));
            if ctx.keeper[wi] {
                blocks[b].keepers.push_str(&ctx.keeper_instance(wi));
            }
            continue;
        }
        if ctx.wire_ports[wi].is_empty() {
            top.signals.push_str(&ctx.signal_decl(wi));
        }
        if ctx.keeper[wi] {
            top.keepers.push_str(&ctx.keeper_instance(wi));
        }
        for &l in &locs {
            let Loc::Block(b) = l else {
                continue;
            };
            // in: the block only reads the wire; out: all its drivers are
            // in the block; inout: the wire has drivers elsewhere too, or a
            // keeper at the top level.
            let drives = w.sources.iter().any(|c| loc(c) == Some(l));
            let all = w.sources.iter().all(|c| loc(c) == Some(l)) && !ctx.keeper[wi];
            let dir = match (drives, all) {
                (false, _) => PortDir::Input,
                (true, true) => PortDir::Output,
                (true, false) if ctx.is_real[wi] => {
                    bail!("analog wire {} is driven from two blocks", w.name)
                }
                (true, false) => PortDir::Inout,
            };
            blocks[b].ports.push((wi, dir));
        }
    }
    Ok(top)
}

/// The package of the default lengths of the ports of the module (and of
/// the gate widths on them), which the blocks read too.
fn param_package(ctx: &Ctx<'_>) -> Result<File> {
    let mut s = String::new();
    writeln!(s, "{HEADER}--")?;
    writeln!(
        s,
        "-- The lengths of the wires on the ports of {}, and the gate widths\n\
         -- on them, unless the level above gives others.\n",
        ctx.module
    )?;
    writeln!(
        s,
        "package {} is",
        vhdl_id(&format!("{}_param", ctx.module))
    )?;
    for p in &ctx.ports {
        let w = &ctx.nl.wires[p.wire];
        let (l_terms, w_terms) = ctx.pin_terms(w);
        let (sum, _) = ctx.length(w)?;
        let l = sum_expr(sum, &l_terms);
        writeln!(
            s,
            "  constant {} : real := {l};",
            vhdl_id(&sv_name(&p.name, "L_"))
        )?;
        if p.dir == PortDir::Output {
            continue;
        }
        let g = sum_expr(Ctx::w_extra(w)?, &w_terms);
        writeln!(
            s,
            "  constant {} : real := {g};",
            vhdl_id(&sv_name(&p.name, "W_gate_"))
        )?;
    }
    writeln!(s, "end package;")?;
    Ok(File {
        path: format!("{}_param.vhd", ctx.module),
        text: s,
    })
}

/// The entity and architecture of a block.
fn block_file(ctx: &Ctx<'_>, b: &Block, label: &str) -> Result<File> {
    let mut s = String::new();
    writeln!(s, "{HEADER}--")?;
    let doc = if b.doc.is_empty() {
        String::new()
    } else {
        format!(" ({})", b.doc)
    };
    writeln!(
        s,
        "-- Block {}{doc} of {}: {} cells. Its ports are the wires it\n\
         -- shares with the other blocks and the pins of {}.\n",
        b.name, ctx.module, b.count, ctx.module
    )?;
    writeln!(s, "library ieee;\nuse ieee.std_logic_1164.all;\n")?;
    writeln!(s, "entity {} is", b.entity)?;
    let generics: Vec<String> = b
        .generic_names(ctx)
        .iter()
        .map(|g| format!("{g} : real"))
        .collect();
    if !generics.is_empty() {
        writeln!(s, "  generic (\n    {}\n  );", generics.join(";\n    "))?;
    }
    let decls: Vec<String> = b
        .ports
        .iter()
        .map(|&(wi, dir)| format!("{} : {} {}", ctx.hdl_name[wi], dir.vhdl(), ctx.sig_type(wi)))
        .collect();
    if !decls.is_empty() {
        writeln!(s, "  port (\n    {}\n  );", decls.join(";\n    "))?;
    }
    writeln!(s, "end entity;\n")?;
    writeln!(s, "architecture gates of {} is", b.entity)?;
    s.push_str(&b.signals);
    writeln!(s, "begin")?;
    s.push_str(&b.cells);
    s.push_str(&b.keepers);
    writeln!(s, "end architecture;")?;
    Ok(File {
        path: format!("{}/{label}.vhd", ctx.module),
        text: s,
    })
}

/// The instance of a block in the module: each port on the wire of the
/// same name.
fn block_instance(ctx: &Ctx<'_>, b: &Block, label: &str) -> Result<String> {
    let mut s = String::new();
    writeln!(s, "  {label} : entity work.{}", b.entity)?;
    let generics: Vec<String> = b
        .generic_names(ctx)
        .iter()
        .map(|g| format!("{g} => {g}"))
        .collect();
    if !generics.is_empty() {
        writeln!(
            s,
            "    generic map (\n      {}\n    )",
            generics.join(",\n      ")
        )?;
    }
    let actuals: Vec<String> = b
        .ports
        .iter()
        .map(|&(wi, _)| format!("{0} => {0}", ctx.hdl_name[wi]))
        .collect();
    if actuals.is_empty() {
        s.truncate(s.trim_end().len());
        s.push_str(";\n");
    } else {
        writeln!(
            s,
            "    port map (\n      {}\n    );",
            actuals.join(",\n      ")
        )?;
    }
    Ok(s)
}

/// The module: its entity, and an architecture that connects the blocks.
fn top_file(ctx: &Ctx<'_>, top: &Top, instances: &str) -> Result<File> {
    let mut s = String::new();
    writeln!(s, "{HEADER}--")?;
    writeln!(
        s,
        "-- {}: the blocks of {}/, connected by the wires they share.\n",
        ctx.module, ctx.module
    )?;
    writeln!(s, "library ieee;\nuse ieee.std_logic_1164.all;\n")?;
    let module_id = vhdl_id(&ctx.module);
    writeln!(s, "entity {module_id} is")?;
    let pkg = format!("work.{}", vhdl_id(&format!("{}_param", ctx.module)));
    let generics: Vec<String> = ctx
        .ports
        .iter()
        .filter(|p| p.dir != PortDir::Input)
        .flat_map(|p| {
            let l = vhdl_id(&sv_name(&p.name, "L_"));
            let g = vhdl_id(&sv_name(&p.name, "W_gate_"));
            let gdef = if p.dir == PortDir::Output {
                "0.0".to_owned()
            } else {
                format!("{pkg}.{g}")
            };
            [
                format!("{l} : real := {pkg}.{l}"),
                format!("{g} : real := {gdef}"),
            ]
        })
        .collect();
    if !generics.is_empty() {
        writeln!(s, "  generic (\n    {}\n  );", generics.join(";\n    "))?;
    }
    let port_decls: Vec<String> = ctx
        .ports
        .iter()
        .map(|p| {
            let ty = if ctx.is_real[p.wire] {
                "real"
            } else {
                "std_logic"
            };
            format!("{} : {} {ty}", vhdl_id(&sv_name(&p.name, "")), p.dir.vhdl())
        })
        .collect();
    writeln!(s, "  port (\n    {}\n  );", port_decls.join(";\n    "))?;
    writeln!(s, "end entity;\n")?;

    writeln!(s, "library ieee;\nuse ieee.std_logic_1164.all;\n")?;
    writeln!(s, "architecture gates of {module_id} is")?;
    s.push_str(&top.signals);
    writeln!(s, "begin")?;
    // A wire on several ports: the other output ports copy the first one.
    for (wi, ps) in ctx.wire_ports.iter().enumerate() {
        for &p in ps.iter().skip(1) {
            if ctx.ports[p].dir != PortDir::Output {
                bail!(
                    "wire {} is connected to several input ports",
                    ctx.nl.wires[wi].name
                );
            }
            let port = vhdl_id(&sv_name(&ctx.ports[p].name, ""));
            writeln!(s, "  {port} <= {};", ctx.hdl_name[wi])?;
        }
    }
    s.push_str(instances);
    s.push_str(&top.cells);
    s.push_str(&top.keepers);
    writeln!(s, "end architecture;")?;
    Ok(File {
        path: format!("{}.vhd", ctx.module),
        text: s,
    })
}

/// The instance of a cell, and the module ports whose generics it uses.
fn instance(ctx: &Ctx<'_>, cell: &Cell) -> Result<(String, Vec<usize>)> {
    let nl = ctx.nl;
    let (generics, used) = cell_generics(ctx, cell)?;
    let mut actuals = Vec::new();
    for p in &nl.type_of(cell).ports {
        let formal = vhdl_id(&sv_name(&p.name, ""));
        let actual = match nl.wire_at(&cell.name, &p.name) {
            Some(wi) => ctx.hdl_name[wi].clone(),
            None if p.dir == Dir::In => "'Z'".to_owned(),
            None if p.dir == Dir::NotConnected => continue,
            None => "open".to_owned(),
        };
        actuals.push(format!("{formal} => {actual}"));
    }
    let mut s = String::new();
    writeln!(
        s,
        "  {} : entity work.{}",
        prefixed("u_", &sv_name(&cell.name, "")),
        vhdl_id(&ctx.entity_of(&cell.type_name))
    )?;
    if !generics.is_empty() {
        writeln!(
            s,
            "    generic map (\n      {}\n    )",
            generics.join(",\n      ")
        )?;
    }
    if actuals.is_empty() {
        // Only for cells without ports (protection diodes).
        s.truncate(s.trim_end().len());
        s.push_str(";\n");
    } else {
        writeln!(
            s,
            "    port map (\n      {}\n    );",
            actuals.join(",\n      ")
        )?;
    }
    Ok((s, used))
}

/// The generics of a cell: the length of the wire on each output and the
/// gate widths on it, then the `sv:` attributes. Also returns the module
/// ports whose generics they use.
fn cell_generics(ctx: &Ctx<'_>, cell: &Cell) -> Result<(Vec<String>, Vec<usize>)> {
    let nl = ctx.nl;
    let mut used = Vec::new();
    let mut generics = Vec::new();
    for p in &nl.type_of(cell).ports {
        if matches!(p.dir, Dir::In | Dir::NotConnected) {
            continue;
        }
        let Some(wi) = nl.wire_at(&cell.name, &p.name) else {
            continue;
        };
        let w = &nl.wires[wi];
        // A wire on an output or inout port of the module takes the length
        // and width of the port, which the level above passes.
        let mut port_par = None;
        let mut is_bidir = false;
        for &mp in &ctx.wire_ports[wi] {
            if ctx.ports[mp].dir == PortDir::Inout {
                is_bidir = true;
            }
            if ctx.ports[mp].dir != PortDir::Input && port_par.is_none() {
                port_par = Some(mp);
            }
        }
        let (sum, given) = ctx.length(w)?;
        if w.coords.is_empty() && !given && port_par.is_none() {
            continue;
        }
        used.extend(port_par);
        let port_par = port_par.map(|mp| &ctx.ports[mp].name);
        let (l_terms, w_terms) = ctx.pin_terms(w);
        let l = match port_par {
            Some(mp) => vhdl_id(&sv_name(mp, "L_")),
            None if l_terms.is_empty() => real_literal(&format_f32(sum)),
            None => format!(
                "{} + {}",
                real_literal(&format_f32(sum)),
                l_terms.join(" + ")
            ),
        };
        generics.push(format!("{} => {l}", vhdl_id(&sv_name(&p.name, "L_"))));
        if w_terms.is_empty() && port_par.is_none() {
            continue;
        }
        let extra = Ctx::w_extra(w)?;
        let mut terms = Vec::new();
        if let Some(mp) = port_par {
            terms.push(vhdl_id(&sv_name(mp, "W_gate_")));
        }
        if !is_bidir && extra != 0.0 {
            terms.push(real_literal(&format_f32(extra)));
        }
        if !is_bidir || port_par.is_none() {
            terms.extend(w_terms);
        }
        let g = if terms.is_empty() {
            "0.0".to_owned()
        } else {
            terms.join(" + ")
        };
        generics.push(format!("{} => {g}", vhdl_id(&sv_name(&p.name, "W_gate_"))));
    }
    for (k, v) in &cell.attribs {
        if let Some(name) = k.strip_prefix("sv:") {
            let e =
                sv::parse_expr(v).with_context(|| format!("cell {}: attribute {k}", cell.name))?;
            generics.push(format!(
                "{} => {}",
                vhdl_id(name.trim()),
                sv::real_expr(&e)?
            ));
        }
    }
    Ok((generics, used))
}

#[cfg(test)]
mod tests {
    use super::*;

    /// Two blocks: `inner` stays in a, `shared` goes from a to b, and `bus`
    /// is driven from both onto an output of the module, with a keeper.
    const NETLIST: &str = r#"
define hdl-module "top";
category a :red; # Block A
category b :red; # Block B
type port x:out q:in;
type not_x1:black in y:out;
type buf_if0:black in ena_n y:tri;
cell port:port virtual;
cell u1:not_x1 ->a;
cell u2:not_x1 ->a;
cell t1:buf_if0 ->a;
cell u3:not_x1 ->b;
cell t2:buf_if0 ->b;
wire x port.x -> u1.in t1.in t2.in;
wire inner u1.y -> u2.in;
wire shared u2.y -> u3.in t1.ena_n t2.ena_n;
wire bus t1.y t2.y -> port.q;
"#;

    fn generate() -> Vec<File> {
        let dir = std::env::temp_dir().join(format!("ceres-hdlgen-{}", std::process::id()));
        std::fs::create_dir_all(&dir).unwrap_or_default();
        let path = dir.join("test.nl");
        std::fs::write(&path, NETLIST).unwrap_or_default();
        let nl = Netlist::read(&[&path], &[]);
        std::fs::remove_dir_all(&dir).unwrap_or_default();
        nl.and_then(|nl| emit(&nl))
            .unwrap_or_else(|e| panic!("{e:#}"))
    }

    #[test]
    fn splits_blocks_by_category() {
        let files = generate();
        let paths: Vec<&str> = files.iter().map(|f| f.path.as_str()).collect();
        assert_eq!(
            paths,
            ["top_param.vhd", "top/a.vhd", "top/b.vhd", "top.vhd"]
        );
        let [_, a, b, top] = &files[..] else {
            unreachable!()
        };
        // A wire used by one block is declared inside it.
        assert!(a.text.contains("  signal n_inner : std_ulogic;"));
        assert!(!top.text.contains("n_inner"));
        // A shared wire is a port: out where all its drivers are, in where
        // it is only read.
        assert!(a.text.contains("n_shared : out std_ulogic"));
        assert!(b.text.contains("n_shared : in std_ulogic"));
        assert!(top.text.contains("  signal n_shared : std_ulogic;"));
        // The pins are ports of the blocks that use them; a wire driven
        // from two blocks is inout in both, with its keeper at the top.
        assert!(a.text.contains("x : in std_logic"));
        assert!(a.text.contains("q : inout std_logic"));
        assert!(b.text.contains("q : inout std_logic"));
        assert!(
            top.text
                .contains("k_bus : entity work.keeper port map (n => q);")
        );
        assert!(top.text.contains("  a : entity work.top_a"));
        assert!(top.text.contains("      n_shared => n_shared"));
    }
}
