//! The console debugger's commands, without a terminal: commands go through
//! `Debugger::execute`, frames through `Debugger::run_frame` as the emulator
//! thread runs them.

#![cfg(feature = "debugger")]
#![expect(clippy::unwrap_used, reason = "tests")]

use ceres_core::{AudioCallback, GbBuilder, Model, Sample};
use ceres_std::debugger::Debugger;
use std::sync::{Arc, Mutex};

struct Silent;

impl AudioCallback for Silent {
    fn audio_sample(&self, _: Sample, _: Sample) {}
}

/// A 64 KiB MBC1 ROM:
///
/// ```text
/// $0100 jp Main
/// $0150 Main:      ld a, 2 ; ld [$2000], a     (maps ROM bank 2)
/// $0155 .loop:     call Sub
/// $0158            call Banked
/// $015B            ld hl, wCounter ; inc [hl]
/// $015F            jr .loop
/// $0200 Sub:       ld b, 5 ; ret
/// 01:4000 Other:   ld c, $11 ; ret             (never mapped)
/// 02:4000 Banked:  ld c, $22 ; ret
/// ```
fn rom() -> Box<[u8]> {
    let mut rom = vec![0; 0x1_0000];
    rom[0x147] = 0x01; // MBC1
    rom[0x148] = 0x01; // 64 KiB
    rom[0x100..0x103].copy_from_slice(&[0xC3, 0x50, 0x01]);
    rom[0x150..0x161].copy_from_slice(&[
        0x3E, 0x02, 0xEA, 0x00, 0x20, // map bank 2
        0xCD, 0x00, 0x02, // call Sub
        0xCD, 0x00, 0x40, // call Banked
        0x21, 0x00, 0xC0, 0x34, // inc [wCounter]
        0x18, 0xF4, // jr .loop
    ]);
    rom[0x200..0x203].copy_from_slice(&[0x06, 0x05, 0xC9]);
    rom[0x4000..0x4003].copy_from_slice(&[0x0E, 0x11, 0xC9]);
    rom[0x8000..0x8003].copy_from_slice(&[0x0E, 0x22, 0xC9]);
    rom.into_boxed_slice()
}

const SYM: &str = "\
; File generated by rgblink
00:0150 Main
00:0155 Main.loop
00:0200 Sub
01:4000 Other
02:4000 Banked
00:c000 wCounter
";

struct Session {
    debugger: Arc<Debugger<Silent>>,
    gb: Arc<Mutex<ceres_core::Gb<Silent>>>,
    stops: Arc<Mutex<Vec<String>>>,
}

impl Session {
    fn new() -> Self {
        let dir = std::env::temp_dir().join(format!(
            "ceres-debugger-{}-{:?}",
            std::process::id(),
            std::thread::current().id()
        ));
        std::fs::create_dir_all(&dir).unwrap();
        std::fs::write(dir.join("game.sym"), SYM).unwrap();

        let gb = GbBuilder::new(48000, Silent)
            .with_model(Model::DmgB)
            .with_run_bootrom(false)
            .with_rom(rom())
            .unwrap()
            .build();
        let gb = Arc::new(Mutex::new(gb));
        let debugger = Debugger::new(Arc::clone(&gb));
        assert_eq!(debugger.load_symbols(Some(&dir.join("game.gb"))), Some(6));
        std::fs::remove_dir_all(&dir).unwrap();

        let stops = Arc::new(Mutex::new(Vec::new()));
        {
            let stops = Arc::clone(&stops);
            debugger.set_printer(move |message| stops.lock().unwrap().push(message));
        }
        Self {
            debugger,
            gb,
            stops,
        }
    }

    fn run(&self, line: &str) -> String {
        self.debugger.execute(line)
    }

    /// Runs frames until the game stops (at most `frames`), and returns
    /// what it printed then.
    fn run_until_stopped(&self, frames: u32) -> Option<String> {
        for _ in 0..frames {
            let mut gb = self.gb.lock().unwrap();
            self.debugger.run_frame(&mut gb);
            drop(gb);
            if self.debugger.is_stopped() {
                return self.stops.lock().unwrap().pop();
            }
        }
        None
    }

    fn pc(&self) -> u16 {
        self.gb.lock().unwrap().cpu_pc()
    }

    /// Stops the running game.
    fn stop(&self) {
        assert_eq!(self.run("interrupt"), "");
        let stop = self.run_until_stopped(1).unwrap();
        assert!(stop.starts_with("Interrupted"), "{stop}");
    }
}

#[test]
fn breakpoints_and_backtrace() {
    let session = Session::new();
    assert_eq!(session.run("b Sub"), "Breakpoint 1: 00:0200 Sub");
    let stop = session.run_until_stopped(2).unwrap();
    assert!(stop.starts_with("Breakpoint 1\n->00:0200 Sub"), "{stop}");
    assert!(stop.contains("ld b, $05"), "{stop}");
    assert_eq!(session.pc(), 0x0200);

    assert_eq!(
        session.run("bt"),
        "  00:0200 Sub\n  00:0200 Sub  called from 00:0155 Main.loop"
    );
    assert_eq!(session.run("list"), "Breakpoint 1: 00:0200 Sub");
    assert_eq!(session.run("delete"), "deleted 1 breakpoints");
}

#[test]
fn stepping() {
    let session = Session::new();
    session.run("b Sub");
    session.run_until_stopped(2).unwrap();
    session.run("delete");

    // `finish` returns from Sub.
    assert_eq!(session.run("finish"), "");
    session.run_until_stopped(1).unwrap();
    assert_eq!(session.pc(), 0x0158);

    // `next` steps over the call to Banked, `step` goes into it.
    assert_eq!(session.run("next"), "");
    session.run_until_stopped(1).unwrap();
    assert_eq!(session.pc(), 0x015B);
    session.run("b Main.loop");
    session.run("c");
    session.run_until_stopped(1).unwrap();
    session.run("delete");
    session.run("s");
    session.run_until_stopped(1).unwrap();
    assert_eq!(session.pc(), 0x0200);
    // An empty line repeats the last command.
    assert_eq!(session.run(""), "");
    session.run_until_stopped(1).unwrap();
    assert_eq!(session.pc(), 0x0202);

    assert_eq!(
        session.run("step"),
        "",
        "stepping works from a stop only, this one is"
    );
    session.run_until_stopped(1).unwrap();
    session.run("c");
    assert!(session.run("step").starts_with("the game is running"));
}

#[test]
fn banks() {
    let session = Session::new();
    // Bank 1 is never mapped: its label at $4000 doesn't stop.
    session.run("b Other");
    assert_eq!(session.run_until_stopped(3), None);
    // Bank 2's does, and so does $4000 in any bank.
    assert_eq!(session.run("b Banked"), "Breakpoint 2: 02:4000 Banked");
    let stop = session.run_until_stopped(1).unwrap();
    assert!(stop.starts_with("Breakpoint 2\n->02:4000 Banked"), "{stop}");
    assert!(stop.contains("ld c, $22"), "{stop}");
    assert_eq!(session.run("delete 2"), "deleted breakpoint 2");
    assert_eq!(session.run("b $4000"), "Breakpoint 3: 4000 (any bank)");
    session.run("c");
    assert!(
        session
            .run_until_stopped(1)
            .unwrap()
            .starts_with("Breakpoint 3")
    );

    // Disassembling reads a bank whether it's mapped or not.
    assert!(session.run("d/1 01:4000").contains("ld c, $11"));
    assert!(session.run("d/1 Other").contains("ld c, $11"));
    assert!(session.run("d/1 $4000").contains("ld c, $22"));
    assert_eq!(
        session.run("cartridge"),
        "ROM0 bank 00  ROMX bank 02  SRAM bank 00"
    );
}

#[test]
fn watchpoints() {
    let session = Session::new();
    assert_eq!(
        session.run("w wCounter if new == 3"),
        "Watchpoint 1: 00:C000 wCounter if new == 3 (writes)"
    );
    let write = session.run_until_stopped(2).unwrap();
    assert!(
        write.starts_with("Watchpoint 1: $03 written to 00:C000 wCounter (was $02)"),
        "{write}"
    );
    // Stopped after the write.
    assert_eq!(session.pc(), 0x015F);
    assert_eq!(session.run("unwatch 1"), "deleted watchpoint 1");
    assert_eq!(
        session.run("w/r wCounter"),
        "Watchpoint 2: 00:C000 wCounter (reads)"
    );
    session.run("c");
    let read = session.run_until_stopped(1).unwrap();
    assert!(
        read.starts_with("Watchpoint 2: $03 read from 00:C000 wCounter"),
        "{read}"
    );
}

#[test]
fn inspecting() {
    let session = Session::new();
    session.stop();
    assert_eq!(session.run("p a = 5"), "$5 (5)");
    assert!(session.run("r").starts_with("AF = $05"));
    assert_eq!(session.run("p/d $10"), "16");
    assert_eq!(session.run("p/b 5"), "%101");
    assert_eq!(session.run("p Sub"), "00:0200 Sub");
    assert_eq!(session.run("p/a Sub + 1"), "00:0201 Sub+1");
    assert_eq!(session.run("x/4 Sub"), "00:0200: 06 05 C9 00");
    assert_eq!(
        session.run("d/2 Sub"),
        "  00:0200 Sub                      ld b, $05\n  00:0202 Sub+2                    ret"
    );
    assert!(session.run("d/1 Main.loop").ends_with("call Sub"));
    assert!(session.run("lcd").starts_with("mode "));
    assert!(session.run("timer").starts_with("DIV counter"));
    assert!(session.run("ints").starts_with("IF = $"));
    assert!(session.run("dma").starts_with("OAM DMA: idle"));
    assert!(session.run("ticks").ends_with("half dots)"));
    assert_eq!(session.run("ticks keep"), "0 dots (0 half dots)");
    assert_eq!(session.run("p nope"), "no register or symbol `nope`");
    assert_eq!(
        session.run("frobnicate"),
        "no command `frobnicate` (try `help`)"
    );
    assert!(session.run("help").contains("breakpoint"));
    assert!(session.run("help w").starts_with("watch /[r|w|rw]"));
}

#[test]
fn states() {
    let session = Session::new();
    session.stop();
    let path = std::env::temp_dir().join(format!("ceres-debugger-{}.bess", std::process::id()));
    let path = path.to_str().unwrap();
    assert!(session.run(&format!("save {path}")).starts_with("saved "));
    let pc = session.pc();
    session.run("p pc = $0200");
    assert_eq!(
        session.run(&format!("load {path}")),
        format!("loaded {path}")
    );
    std::fs::remove_file(path).unwrap();
    assert_eq!(session.pc(), pc);
    assert!(
        session
            .run("load /nonexistent")
            .starts_with("load: /nonexistent")
    );
}
